        $(document).ready(function () {
            var $sidebar = $('.sidebar');
            var $main = $('.main');

            // ★ fixed일 때 sidebar를 main 우측에서 12px 떨어지게 하는 함수
            function updateSidebarRight() {
                var mainRect = $main[0].getBoundingClientRect();
                var rightPos = window.innerWidth - mainRect.right - 3;
                $sidebar.css('right', rightPos + 'px');
            }

            var floatPosStart = $sidebar.offset().top - parseFloat($sidebar.css('marginTop').replace(/auto/, 0));
            var floatPosEnd = $main.offset().top + $main.innerHeight() - $sidebar.outerHeight(true);

            $(window).on('scroll resize', function () {
                var y = $(this).scrollTop();

                if (y >= floatPosStart && y <= floatPosEnd) {
                    // fixed 상태
                    $sidebar.removeClass('sidebar-top sidebar-bottom').addClass('sidebar-fixed');
                    updateSidebarRight();  // ★ fixed일 때 우측 위치 업데이트
                } else if (y >= floatPosEnd) {
                    // absolute-bottom 상태
                    $sidebar.removeClass('sidebar-fixed sidebar-top').addClass('sidebar-bottom');
                    $sidebar.css('right', '12px');  // ★ absolute일 때 right:0
                } else {
                    // absolute-top 상태
                    $sidebar.removeClass('sidebar-fixed sidebar-bottom').addClass('sidebar-top');
                    $sidebar.css('right', '12px');  // ★ absolute일 때 right:0
                }
            });

            // 초기 실행
            updateSidebarRight();
        });
    </script>
