    <script>
        const updateConfirmButton = () => {
            const confirmButton = document.querySelector('.confirm_btn');
            const isDateSelected = document.querySelector('.week_date .date.selected');
            const isOptionSelected = document.querySelector('.prd_opt:checked');

            confirmButton.disabled = !(isDateSelected && isOptionSelected);
            confirmButton.textContent = isDateSelected && isOptionSelected ? '예약 확정' : '예약 일정을 선택하세요.';
        };

        document.querySelectorAll('.week_date .date:not(.disabled):not(.hide)').forEach((date) => {
            date.addEventListener('click', () => {
                document.querySelectorAll('.week_date .date').forEach((item) => item.classList.remove('selected'));
                date.classList.add('selected');
                updateConfirmButton();
            });
        });

        document.querySelectorAll('.prd_opt').forEach((option) => {
            option.addEventListener('change', updateConfirmButton);
        });
    </script>

